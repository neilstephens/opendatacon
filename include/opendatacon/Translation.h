/*
 * Translation.h
 *
 *  Generic (de)serialisation of EventInfo to/from protocol payloads and keys.
 *  Extracted from KafkaPort so other ports can reuse it.
 */

#ifndef ODC_TRANSLATION_H
#define ODC_TRANSLATION_H

#include <opendatacon/IOTypes.h>
#include <opendatacon/LogHelpers.h>
#include <cstdint>
#include <functional>
#include <memory>
#include <optional>
#include <string>
#include <unordered_map>
#include <vector>

namespace odc
{

//How payloads are translated
enum class EventTranslationMethod
{
	Lua,
	Template,
	CBOR
};

//How keys are translated
enum class KeyTranslationMethod
{
	Literal,
	Template,
	CBOR,
	Lua
};

//Which event attribute (if any) is used as the Source part of a point's TranslationID
enum class SourceLookupMethod
{
	SenderName,
	SourcePort,
	None
};

//How to treat keys that are associated with more than one (de)serialiser
//	STRICT:  config error
//	WARN:    warn, and the first one wins
//	DYNAMIC: keys may be non-static (evaluated per event, never cached),
//	         no clash detection, and unmatched keys fall back to the default deserialiser
enum class KeyClashDetection
{
	STRICT,
	WARN,
	DYNAMIC
};

//Which side of a translation a (de)serialiser is for
enum class TranslationRole
{
	Payload,
	Key
};

//Extra, per-point, name/value pairs. Available to serialisers as <POINT:name> placeholders
using ExtraPointFields = std::unordered_map<std::string, std::string>;

struct TranslationConfig
{
	std::string DateTimeFormat = "%Y-%m-%d %H:%M:%S.%e";
	bool DateTimeIsUTC = false;
	DataToStringMethod OctetStringFormat = DataToStringMethod::Base64;
	bool RegexEscapeTemplates = true;
	//the name of the log that the (de)serialisers will log to
	std::string LogName = "opendatacon";
};

//What the key says about which point a message is for
struct PointIdentity
{
	EventType Type = EventType::BeforeRange;
	size_t Index = 0;
	std::optional<std::string> SourcePort;
};

//Passed to deserialisers along with the payload
struct KeyContext
{
	const uint8_t* Key = nullptr;
	size_t KeySize = 0;
	//Set when the key (which must have been generated by a non-literal key serialiser)
	//	maps to exactly one point. The key wins over anything in the payload.
	std::optional<PointIdentity> Hint;
};

class ISerialiser
{
public:
	virtual ~ISerialiser() = default;
	virtual std::vector<uint8_t> Serialise(const std::shared_ptr<const EventInfo>& event, const std::string& SenderName, const ExtraPointFields& extra_fields) const = 0;
	//Returns a description of the first element that makes the output depend on more than the
	//	point identity (eg. <TIMESTAMP>), or an empty string if the output is static for any one point.
	//	<SENDERNAME> and <SOURCEPORT> are static only if they are the point lookup source.
	virtual std::string FindNonStaticElement(SourceLookupMethod /*lookup*/) const { return ""; }
};

class IDeserialiser
{
public:
	virtual ~IDeserialiser() = default;
	virtual std::shared_ptr<EventInfo> Deserialise(const uint8_t* data, size_t size, const KeyContext& key) = 0;
};

//A serialiser for a fixed key
class LiteralSerialiser: public ISerialiser
{
public:
	explicit LiteralSerialiser(std::vector<uint8_t> bytes): Bytes(std::move(bytes)) {}
	std::vector<uint8_t> Serialise(const std::shared_ptr<const EventInfo>&, const std::string&, const ExtraPointFields&) const override
	{ return Bytes; }
private:
	const std::vector<uint8_t> Bytes;
};

//Factory/registry for (de)serialisers by translation method.
//	Template and CBOR are built in. Other methods can be registered by the module that implements them.
//	Lua is implemented by the LuaWrappers library: if it hasn't been registered when Lua is first needed,
//	the factory loads the LuaWrappers shared library (if there is one) and registers it.
class TranslationFactory
{
public:
	struct Spec
	{
		//Template string, CBOR structure (JSON), or Lua code
		std::string Content;
		//Where the content came from (eg. a Lua file name), for error messages
		std::string Origin;
	};
	using SerialiserCreator = std::function<std::shared_ptr<ISerialiser>(const Spec&, const TranslationConfig&, TranslationRole)>;
	using DeserialiserCreator = std::function<std::shared_ptr<IDeserialiser>(const Spec&, const TranslationConfig&)>;

	static void Register(EventTranslationMethod method, SerialiserCreator serialiser, DeserialiserCreator deserialiser);
	//whether an implementation has been registered (doesn't try to load anything)
	static bool IsRegistered(EventTranslationMethod method);
	//whether an implementation is registered, or can be: tries to load the Lua implementation if needed
	static bool IsAvailable(EventTranslationMethod method);

	//these throw std::runtime_error on failure (bad spec, or unregistered method)
	static std::shared_ptr<ISerialiser> CreateSerialiser(EventTranslationMethod method, const Spec& spec, const TranslationConfig& config, TranslationRole role = TranslationRole::Payload);
	static std::shared_ptr<IDeserialiser> CreateDeserialiser(EventTranslationMethod method, const Spec& spec, const TranslationConfig& config);
};

//The default payload template and CBOR structure
std::string DefaultJSONwPlaceholders();
std::string DefaultCBORStructure();

} //namespace odc

#endif // ODC_TRANSLATION_H
